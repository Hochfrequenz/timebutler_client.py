"""Regenerate src/timebutler_client/models/v2/_generated.py from the pinned OpenAPI spec.

Usage: uv run --group codegen python scripts/generate_v2_models.py
"""

import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
SPEC_PATH = REPO_ROOT / "spec" / "timebutler-v2-openapi.json"
OUTPUT_PATH = REPO_ROOT / "src" / "timebutler_client" / "models" / "v2" / "_generated.py"


def generate(output: Path) -> None:
    """
    Run datamodel-codegen with the project's fixed options and write the result to `output`.

    The code is always generated next to OUTPUT_PATH first, because the ruff formatters pick up
    their configuration (line length, first-party packages) from the location of the generated file.
    """
    with tempfile.TemporaryDirectory(dir=OUTPUT_PATH.parent) as tmp_dir:
        tmp_output = Path(tmp_dir) / OUTPUT_PATH.name
        _run_codegen(tmp_output)
        shutil.copyfile(tmp_output, output)


def _run_codegen(output: Path) -> None:
    subprocess.run(
        [
            sys.executable,
            "-m",
            "datamodel_code_generator",
            "--input",
            str(SPEC_PATH),
            "--input-file-type",
            "openapi",
            "--output",
            str(output),
            "--output-model-type",
            "pydantic_v2.BaseModel",
            "--base-class",
            "timebutler_client.models.v2._base.V2BaseModel",
            "--snake-case-field",
            "--allow-population-by-field-name",
            "--use-standard-collections",
            "--use-union-operator",
            "--target-python-version",
            "3.11",
            "--enum-field-as-literal",
            "all",
            "--use-field-description",
            "--use-schema-description",
            "--use-double-quotes",
            "--disable-timestamp",
            "--formatters",
            "ruff-check",
            "ruff-format",
            "--custom-file-header",
            "# generated by scripts/generate_v2_models.py — DO NOT EDIT",
        ],
        check=True,
        cwd=REPO_ROOT,
    )


if __name__ == "__main__":
    generate(OUTPUT_PATH)
